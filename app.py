# -*- coding: utf-8 -*-
"""
Gradio Web Interface
--------------------
This is the front-end of our application -- the page users interact with.

We use Gradio because:
  - It's pure Python (no HTML/CSS/JS needed)
  - Builds a clean web UI with just a few lines
  - You already used it in your original project!

The UI has two tabs:
  Tab 1 -- Job Search: user fills in their details, crew runs, report appears
  Tab 2 -- About:      explains the project architecture for the assignment
"""

import gradio as gr
from crew import run_job_search_crew
from monitoring.langfuse_config import get_monitoring_status


# ------------------------------------------------------------------ #
# Helper: format the final report nicely for display
# ------------------------------------------------------------------ #
def format_output(result: str) -> str:
    """Adds a header and footer to the crew's output for display."""
    return (
        "## Your Personalised Job Search Report\n\n"
        + result
        + "\n\n---\n*Generated by Job Search CrewAI -- powered by GPT-4o-mini, Tavily & Remotive*"
    )


# ------------------------------------------------------------------ #
# Main function: called when user clicks "Run Job Search"
# ------------------------------------------------------------------ #
def run_search(job_title, location, candidate_profile, job_description):
    """
    Validates inputs, runs the crew, and returns the result for display.
    This function is wired to the Gradio button click event below.
    """

    # Input validation (fallback before even calling the crew)
    if not job_title.strip():
        yield "Please enter a job title before running the search."
        return

    if not candidate_profile.strip():
        yield "Please enter your skills/experience so the Career Advisor can score your fit."
        return

    if len(candidate_profile.strip()) < 30:
        yield "Your candidate profile is too short. Please add more detail about your skills and experience."
        return

    # Build the user inputs dict (passed to crew.py -> tasks.py)
    user_inputs = {
        "job_title": job_title.strip(),
        "location": location.strip() if location.strip() else "Remote",
        "candidate_profile": candidate_profile.strip(),
        "job_description": job_description.strip() if job_description.strip() else "Not provided",
    }

    # Show a status message while running
    yield (
        "**Running your job search crew... This takes 1-2 minutes.**\n\n"
        "Here is what is happening:\n"
        "1. Job Researcher is searching for listings...\n"
        "2. Salary Analyst is looking up compensation data...\n"
        "3. Job Analyst is summarizing the job description...\n"
        "4. Career Advisor is scoring your profile fit...\n\n"
        "Please wait..."
    )

    # Run the crew
    result = run_job_search_crew(user_inputs)

    # Yield the final formatted result
    yield format_output(result)


# ------------------------------------------------------------------ #
# Build the Gradio UI
# ------------------------------------------------------------------ #
def build_ui():

    monitoring = get_monitoring_status()
    monitoring_badge = (
        "Monitoring: ON (Langfuse connected)"
        if monitoring["enabled"]
        else "Monitoring: OFF (set Langfuse keys in .env)"
    )

    with gr.Blocks(title="Job Search CrewAI Assistant") as demo:

        # Header
        gr.Markdown(
            "# Job Search CrewAI Assistant\n"
            "### A multi-agent AI system that finds jobs, researches salaries, and scores your profile fit\n\n"
            "*Built with CrewAI, GPT-4o-mini, Tavily, Remotive, Langfuse*"
        )

        gr.Markdown(f"`{monitoring_badge}`")

        # ---- TAB 1: Job Search ---- #
        with gr.Tab("Job Search"):

            gr.Markdown(
                "### How it works\n"
                "Fill in the fields below and click **Run Job Search**. Four AI agents will collaborate:\n"
                "1. **Job Researcher** -- finds live job listings\n"
                "2. **Salary Analyst** -- researches compensation benchmarks\n"
                "3. **Job Analyst** -- summarizes the job description you paste\n"
                "4. **Career Advisor** -- scores your fit and gives recommendations\n"
            )

            with gr.Row():
                with gr.Column(scale=1):
                    job_title = gr.Textbox(
                        label="Job Title (required)",
                        placeholder="e.g. Data Scientist, Backend Developer, Product Manager",
                        value="Data Scientist",
                    )
                    location = gr.Textbox(
                        label="Location / Work Type",
                        placeholder="e.g. Malaysia, Singapore, Remote, London",
                        value="Remote",
                    )

            candidate_profile = gr.Textbox(
                label="Your Skills & Experience (required)",
                placeholder=(
                    "Describe your background, key skills, years of experience, "
                    "education, and any relevant projects.\n\n"
                    "Example:\n"
                    "3 years of experience in Python, pandas, and scikit-learn. "
                    "BSc Computer Science. Built ML models for customer churn prediction. "
                    "Familiar with SQL, Tableau, and basic NLP."
                ),
                lines=6,
            )

            job_description = gr.Textbox(
                label="Job Description to Analyse (optional -- paste a specific job posting)",
                placeholder=(
                    "Paste the full text of a job posting you are interested in.\n"
                    "The Job Analyst will summarize it and the Career Advisor will score your fit.\n\n"
                    "If left empty, the agents will work with the job listings they find."
                ),
                lines=8,
            )

            with gr.Row():
                run_btn = gr.Button("Run Job Search", variant="primary", size="lg")
                clear_btn = gr.Button("Clear", variant="secondary")

            output = gr.Markdown(
                value="*Results will appear here after you run the search.*"
            )

            # Wire the button to the function
            run_btn.click(
                fn=run_search,
                inputs=[job_title, location, candidate_profile, job_description],
                outputs=output,
            )

            clear_btn.click(
                fn=lambda: ("", "", "", "", "*Results will appear here after you run the search.*"),
                outputs=[job_title, location, candidate_profile, job_description, output],
            )

        # ---- TAB 2: About / Architecture ---- #
        with gr.Tab("About This Project"):
            gr.Markdown(
                "## About This Application\n\n"
                "This project is a **CrewAI-based multi-agent job search assistant**, built as an extension\n"
                "of the original [job-search-assistant](https://github.com/arahmanmdmajid/job-search-assistant)\n"
                "which used LangGraph.\n\n"
                "---\n\n"
                "## Architecture\n\n"
                "### Agents\n"
                "| Agent | Role | Tool |\n"
                "|---|---|---|\n"
                "| Job Market Researcher | Finds live job listings | Tavily Search API |\n"
                "| Salary Analyst | Research compensation benchmarks | Remotive API |\n"
                "| Job Description Analyst | Summarizes job postings | GPT-4o-mini (custom) |\n"
                "| Career Advisor | Scores candidate-job fit | Resume Matcher (custom) |\n\n"
                "### Workflow (Sequential Process)\n"
                "```\n"
                "Task 1: Research Jobs  ->  Task 2: Salary Research\n"
                "                       ->  Task 3: Summarize Job Description\n"
                "                       (all outputs combined)\n"
                "                      Task 4: Match & Final Report\n"
                "```\n\n"
                "### Tools\n"
                "- **Job Search Tool** -- queries Tavily API for live listings\n"
                "- **Salary Research Tool** -- pulls compensation data from Remotive\n"
                "- **Job Description Summarizer** -- structured GPT-4o-mini summarization\n"
                "- **Resume Matcher** (custom) -- scores candidate fit 0-100 with strengths/gaps\n\n"
                "### Fallback Handling\n"
                "- API failures caught with try/except in every tool\n"
                "- Crew retried up to 2 times before returning a friendly error message\n"
                "- Empty/invalid outputs detected and handled gracefully\n\n"
                "### Observability (Langfuse)\n"
                "When Langfuse keys are configured, every agent execution, LLM call,\n"
                "tool call, token count, and latency is automatically tracked at:\n"
                "[cloud.langfuse.com](https://cloud.langfuse.com)\n\n"
                "---\n\n"
                "## MCP (Model Context Protocol) Awareness\n\n"
                "**Tools that could be MCP servers:**\n"
                "- The Tavily job search could be exposed as an MCP server so any agent\n"
                "  or application can call it without re-implementing the API client\n"
                "- The Remotive salary tool could be a standardised MCP data source\n"
                "- A resume/CV parser could be an MCP server shared across projects\n\n"
                "**Benefits of MCP here:**\n"
                "- Tool definitions would be standardised (no duplicating @tool wrappers)\n"
                "- New agents could discover and use tools dynamically\n"
                "- The Resume Matcher could become a reusable MCP server for any career app\n\n"
                "---\n\n"
                "*Built with: CrewAI, OpenAI GPT-4o-mini, Tavily, Remotive, Langfuse, Gradio*\n"
            )

    return demo


# ------------------------------------------------------------------ #
# Entry point
# ------------------------------------------------------------------ #
if __name__ == "__main__":
    demo = build_ui()
    demo.launch(
        server_name="0.0.0.0",
        server_port=7860,
        share=False,
        show_error=True,
        theme=gr.themes.Soft(),
    )
